package web

import (
	"bytes"
	"html/template"
	"io"

	"github.com/gomarkdown/markdown"
	"github.com/gomarkdown/markdown/ast"
	"github.com/gomarkdown/markdown/html"
	"github.com/gomarkdown/markdown/parser"
)

// TOCEntry represents a table of contents entry
type TOCEntry struct {
	ID    string
	Title string
	Level int
}

// DocumentContent holds rendered markdown and its TOC
type DocumentContent struct {
	HTML template.HTML
	TOC  []TOCEntry
}

// renderMarkdownWithTOC converts markdown text to HTML and extracts TOC entries
func renderMarkdownWithTOC(text string) DocumentContent {
	// Create markdown parser with common extensions
	extensions := parser.CommonExtensions | parser.AutoHeadingIDs
	p := parser.NewWithExtensions(extensions)

	// Parse markdown
	doc := p.Parse([]byte(text))

	// Extract TOC entries from the AST
	toc := extractTOC(doc)

	// Create HTML renderer with safe options
	opts := html.RendererOptions{
		Flags: html.CommonFlags | html.HrefTargetBlank | html.SkipHTML,
		// Add rel="nofollow" to external links
		RenderNodeHook: func(w io.Writer, node ast.Node, entering bool) (ast.WalkStatus, bool) {
			if link, ok := node.(*ast.Link); ok && entering {
				io.WriteString(w, "<a href=\"")
				html.EscapeHTML(w, link.Destination)
				io.WriteString(w, "\" rel=\"nofollow\" target=\"_blank\">")
				return ast.GoToNext, true
			}
			return ast.GoToNext, false
		},
	}
	renderer := html.NewRenderer(opts)

	// Render to HTML
	htmlBytes := markdown.Render(doc, renderer)

	return DocumentContent{
		HTML: template.HTML(htmlBytes),
		TOC:  toc,
	}
}

// extractTOC walks the markdown AST and extracts headings for the table of contents
func extractTOC(doc ast.Node) []TOCEntry {
	var toc []TOCEntry

	ast.WalkFunc(doc, func(node ast.Node, entering bool) ast.WalkStatus {
		if !entering {
			return ast.GoToNext
		}

		if heading, ok := node.(*ast.Heading); ok {
			// Extract heading ID (auto-generated by parser)
			id := heading.HeadingID

			// Extract heading text
			var buf bytes.Buffer
			for _, child := range heading.Children {
				if text, ok := child.(*ast.Text); ok {
					buf.Write(text.Literal)
				}
			}

			toc = append(toc, TOCEntry{
				ID:    id,
				Title: buf.String(),
				Level: heading.Level,
			})
		}

		return ast.GoToNext
	})

	return toc
}
